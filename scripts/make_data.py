"""Write the work order cases and the 15 simulated shift logs. Deterministic: same files every time."""

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from cabling.simulate import write_all
from cabling.workorder import cases

header = "# Generated by scripts/make_data.py: one case per connection slot in a rack (90).\n"
(ROOT / "evals" / "shift" / "cases.yml").write_text(header + yaml.safe_dump(cases(), sort_keys=False, width=120))
paths = write_all(ROOT / "data" / "shifts")
print(f"wrote {len(cases())} cases and {len(paths)} shift logs")
