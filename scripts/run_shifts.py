"""Grade all 15 shifts with the shift gate, work out the pilot stage, and write the weekly fact sheets.

Writes:
  reports/shifts/NN/        golive-gate report for each shift (report.md, results.json, index.html)
  data/pilot.json           per-shift numbers, gate decisions and the stage timeline
  evals/summary/cases.yml   one fact sheet per week: the only numbers the customer update may use
"""

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from golive_gate import evaluate, run_eval
from golive_gate import report as golive_report
from golive_gate.config import load_project

from cabling.recorded import ROOT as REC
from cabling.recorded import Tape, key
from cabling.simulate import SHIFTS
from cabling.stages import metrics, timeline, weekly_facts

# Modules a golive project imports from an evals folder. They hold a module-level recording Tape,
# whose replay queue drains as it is read, so a second grading of the same project in one process
# must start from fresh modules. golive only evicts modules from a different root, not a second
# load of the same one, so we evict these by hand before each load_project.
_PROJECT_MODULES = ("agent", "checks", "judge_checks")


def fresh_project(config: Path, **kw):
    """load_project with the project's own modules reimported, so recording tapes start full."""
    for name in _PROJECT_MODULES:
        sys.modules.pop(name, None)
    return load_project(config, **kw)


def notes_gate_decision():
    """Grade the recorded notes run on fresh modules and return (decision, drained project)."""
    p = fresh_project(ROOT / "evals" / "notes" / "golive.yml")
    return evaluate(p.gate, run_eval(p.agent, p.cases, p.checks, runs=p.runs)).decision


def blocking_shifts() -> tuple[set[int], str]:
    """Shifts with a tech note tagged as blocking unsupervised work.

    Uses the recorded Claude triage (first run) only when it exists and the notes gate says GO;
    otherwise falls back to the hand labels in evals/notes/cases.yml and says why.
    """
    cases = yaml.safe_load((ROOT / "evals" / "notes" / "cases.yml").read_text())
    labels = {c["input"]["shift"] for c in cases if c["expected"]["blocks_unsupervised"]}
    tape = Tape(REC / "notes_agent.jsonl")
    if not tape.exists():
        return labels, "hand labels (no recorded Claude triage yet)"
    decision = notes_gate_decision()
    if decision != "go":
        return labels, f"hand labels (recorded Claude triage gate is {decision})"
    # Read the recording straight from the file, so nothing here drains a tape the demo build reuses.
    blocked = {c["input"]["shift"] for c in cases if tape.next(key(c["input"]))["blocks_unsupervised"]}
    return blocked, "Claude triage (recorded run, notes gate GO)"


def main(out: Path) -> dict:
    decisions, copper_ok, shift_metrics = [], [], []
    for shift in range(1, SHIFTS + 1):
        project = load_project(ROOT / "evals" / "shift" / "golive.yml", agent=f"agent:shift_{shift:02d}")
        result = run_eval(project.agent, project.cases, project.checks, runs=1)
        outcome = evaluate(project.gate, result)
        golive_report.write(out / f"{shift:02d}", result, project.gate, outcome, agent=f"robot log, shift {shift}")
        decisions.append(outcome.decision)
        copper_held = all(o.held for o in outcome.outcomes if o.rule.groups == ("copper",))
        copper_ok.append(copper_held and not outcome.critical.get(1))
        shift_metrics.append(metrics([cr.output for cr in result.case_runs], outcome.decision))
    blocked, source = blocking_shifts()
    tl = timeline(decisions, blocked, copper_ok)
    weeks = weekly_facts(shift_metrics, tl)
    pilot = {"shifts": shift_metrics, "timeline": tl, "weeks": weeks, "blocking_notes_from": source}
    (ROOT / "data" / "pilot.json").write_text(json.dumps(pilot, indent=2) + "\n")
    cases = [{"id": f"week{w['week']}", "title": f"Week {w['week']} update", "input": w} for w in weeks]
    header = "# Generated by scripts/run_shifts.py from the 15 graded shifts. One fact sheet per week.\n"
    (ROOT / "evals" / "summary" / "cases.yml").write_text(header + yaml.safe_dump(cases, sort_keys=False))
    return pilot


if __name__ == "__main__":
    pilot = main(ROOT / "reports" / "shifts")
    for t in pilot["timeline"]:
        flag = " blocking note" if t["blocking_note"] else ""
        print(f"shift {t['shift']:2d}: {t['decision']:8s}{flag:14s} streak {t['go_streak']:2d}", end="")
        print(f"  next: {t['next_stage']}")
    print(f"blocking notes from: {pilot['blocking_notes_from']}")
